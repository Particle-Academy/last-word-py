"""Windows code pages, for the bytes a legacy format stores as 8-bit text.

Mirrors PHP `Reader\\CodePage` and Node `reader/code-page.ts`.

The single-byte pages carry their upper half as a table of 128 code points (four
hex digits each), generated from the Unicode mappings Python's codecs ship. A
byte a page leaves undefined maps to the C1 control of the same value, as the
WHATWG encoding standard does, so decoding never fails.

`bytes.decode("cp1252")` is deliberately not used: it RAISES on those undefined
bytes, and the three engines must decode identically, so all three read the
same table.

The double-byte pages (932 Japanese, 936 Simplified Chinese, 949 Korean, 950
Traditional Chinese) are NOT decoded, though Python could: the PHP and Node
engines cannot without tens of thousands of table entries, and a third engine
that decodes what the other two replace would disagree with them on the same
bytes. A double-byte character becomes U+FFFD, one per character rather than one
per byte, and 932's single-byte katakana are decoded.

Any other code page is read as 1252.
"""

