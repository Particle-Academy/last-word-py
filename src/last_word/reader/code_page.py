_DOUBLE_BYTE = (932, 936, 949, 950)


def is_known_code_page(codepage: int) -> bool:
    return codepage in _SINGLE_BYTE or codepage in _DOUBLE_BYTE


def decode_code_page(data: bytes | bytearray | list[int], codepage: int) -> str:
    """Bytes in the code page, as a string."""
    page = codepage if is_known_code_page(codepage) else DEFAULT_CODE_PAGE
    double = page in _DOUBLE_BYTE
    table = _SINGLE_BYTE.get(page, "")

    out: list[str] = []
    i = 0
    length = len(data)
    while i < length:
        byte = data[i]
        if byte < 0x80:
            out.append(chr(byte))
        elif not double:
            offset = (byte - 0x80) * 4
            out.append(from_code_point(int(table[offset : offset + 4], 16)))
        elif page == 932 and 0xA1 <= byte <= 0xDF:
            out.append(chr(0xFF61 + byte - 0xA1))  # half-width katakana
        elif _is_lead_byte(byte, page):
            i += 1  # the trail byte belongs to this character
            out.append(REPLACEMENT)
        else:
            out.append(REPLACEMENT)
        i += 1

    return "".join(out)


def _is_lead_byte(byte: int, codepage: int) -> bool:
    if codepage == 932:
        return 0x81 <= byte <= 0x9F or 0xE0 <= byte <= 0xFC
    return 0x81 <= byte <= 0xFE


def from_code_point(cp: int) -> str:
    """A code point as a string; half a surrogate pair, or past U+10FFFF, is U+FFFD."""
    if 0xD800 <= cp <= 0xDFFF or cp > 0x10FFFF or cp < 0:
        return REPLACEMENT
    return chr(cp)
